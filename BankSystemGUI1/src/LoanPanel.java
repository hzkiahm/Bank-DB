    private void searchloannumActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchloannumActionPerformed
         String inputLoanNum = JOptionPane.showInputDialog(this, "Enter Loan Number to Search:");

    if (inputLoanNum == null || inputLoanNum.trim().isEmpty()) {
        return;
    }

    try {
        int loanNumber = Integer.parseInt(inputLoanNum.trim());

        String sql = "SELECT * FROM Loan WHERE loannum = ?";

        java.sql.Connection con = DBConnection.getConnection();
        java.sql.PreparedStatement pst = con.prepareStatement(sql);
        pst.setInt(1, loanNumber);

        java.sql.ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            DefaultTableModel model = new DefaultTableModel(
                new String[]{"Loan Number", "Account Number", "Loan Amount", "Loan Type", "Status"}, 0
            );

            model.addRow(new Object[]{
                rs.getInt("loannum"),
                rs.getInt("accnum"),
                rs.getDouble("loanamount"),
                rs.getString("loantype"),
                rs.getString("status")
            });

            JTable table = new JTable(model);

            JFrame resultFrame = new JFrame("Search Result");
            resultFrame.add(new javax.swing.JScrollPane(table));
            resultFrame.setSize(800, 150);
            resultFrame.setLocationRelativeTo(this);
            resultFrame.setVisible(true);

        } else {
            JOptionPane.showMessageDialog(this, "No record found for Loan Number: " + inputLoanNum);
        }

        rs.close();
        pst.close();
        con.close();

    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Loan number must be a number.");
    } catch (java.sql.SQLException ex) {
        JOptionPane.showMessageDialog(this, "Error searching record: " + ex.getMessage());
    }
    }//GEN-LAST:event_searchloannumActionPerformed

