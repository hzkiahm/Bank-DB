    private void updateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateActionPerformed
        String codeText = bankcode.getText().trim();
        String newName = bankname.getText().trim();
        String newAddress = bankadd.getText().trim();

        if (codeText.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Enter bank code first.");
            bankcode.requestFocus();
            return;
        }

        if (newName.isEmpty() || newAddress.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Bank name and address cannot be empty.");
            return;
        }

        try {
            int code = Integer.parseInt(codeText);

            java.sql.Connection con = DBConnection.getConnection();

            String selectSql = "SELECT bankname, bankadd FROM Bank WHERE bankcode = ?";
            java.sql.PreparedStatement selectPst = con.prepareStatement(selectSql);
            selectPst.setInt(1, code);
            java.sql.ResultSet rs = selectPst.executeQuery();

            if (!rs.next()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Bank code not found.");
                rs.close();
                selectPst.close();
                con.close();
                return;
            }

            String currentName = rs.getString("bankname");
            String currentAddress = rs.getString("bankadd");

            rs.close();
            selectPst.close();

            String message = "Are you sure you want to update this bank record?\n\n"
                    + "Current Information:\n"
                    + "Bank Code: " + code + "\n"
                    + "Bank Name: " + currentName + "\n"
                    + "Address: " + currentAddress + "\n\n"
                    + "New Information:\n"
                    + "Bank Code: " + code + "\n"
                    + "Bank Name: " + newName + "\n"
                    + "Address: " + newAddress;

            int confirm = javax.swing.JOptionPane.showConfirmDialog(
                    this,
                    message,
                    "Confirm Update",
                    javax.swing.JOptionPane.YES_NO_OPTION
            );

            if (confirm != javax.swing.JOptionPane.YES_OPTION) {
                con.close();
                return;
            }

            String updateSql = "UPDATE Bank SET bankname = ?, bankadd = ? WHERE bankcode = ?";
            java.sql.PreparedStatement updatePst = con.prepareStatement(updateSql);

            updatePst.setString(1, newName);
            updatePst.setString(2, newAddress);
            updatePst.setInt(3, code);

            int rows = updatePst.executeUpdate();

            if (rows > 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Bank record updated successfully.");
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Update failed.");
            }

            updatePst.close();
            con.close();

        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Bank code must be a number.");
        } catch (java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error updating record: " + ex.getMessage());
        }
    }//GEN-LAST:event_updateActionPerformed

