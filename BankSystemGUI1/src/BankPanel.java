    private void searchbcodeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchbcodeActionPerformed
        String inputCode = JOptionPane.showInputDialog(this, "Enter Bank Code to Search:");

        if (inputCode == null || inputCode.trim().isEmpty()) {
            return;
        }

        try {
            int code = Integer.parseInt(inputCode.trim());

            String sql = "SELECT * FROM Bank WHERE bankcode = ?";

            Connection con = DBConnection.getConnection();
            PreparedStatement pst = con.prepareStatement(sql);
            pst.setInt(1, code);

            ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                DefaultTableModel model = new DefaultTableModel(
                    new String[]{"Bank Code", "Bank Name", "Address"}, 0
                );

                model.addRow(new Object[]{
                    rs.getInt("bankcode"),
                    rs.getString("bankname"),
                    rs.getString("bankadd")
                });

                JTable table = new JTable(model);

                JFrame resultFrame = new JFrame("Search Result");
                resultFrame.add(new javax.swing.JScrollPane(table));
                resultFrame.setSize(600, 150);
                resultFrame.setLocationRelativeTo(this);
                resultFrame.setVisible(true);

            } else {
                JOptionPane.showMessageDialog(this, "No record found for Bank Code: " + inputCode);
            }

            rs.close();
            pst.close();
            con.close();

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Bank code must be a number.");
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error searching record: " + ex.getMessage());
        }
    }//GEN-LAST:event_searchbcodeActionPerformed

