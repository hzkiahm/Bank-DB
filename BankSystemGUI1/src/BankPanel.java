    private void saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveActionPerformed
        String codeText = bankcode.getText().trim();
        String name = bankname.getText().trim();
        String address = bankadd.getText().trim();

        if (codeText.isEmpty() || name.isEmpty() || address.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please fill in all fields.");
            return;
        }

        try {
            int code = Integer.parseInt(codeText);

            String sql = "INSERT INTO Bank (bankcode, bankname, bankadd) VALUES (?, ?, ?)";

            java.sql.Connection con = DBConnection.getConnection();
            java.sql.PreparedStatement pst = con.prepareStatement(sql);

            pst.setInt(1, code);
            pst.setString(2, name);
            pst.setString(3, address);

            pst.executeUpdate();

            javax.swing.JOptionPane.showMessageDialog(this, "Bank saved successfully.");

            pst.close();
            con.close();

        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Bank code must be a number.");
        } catch (java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }
    }//GEN-LAST:event_saveActionPerformed

    private void deleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteActionPerformed
        String codeText = bankcode.getText().trim();

        if (codeText.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Enter bank code first.");
            return;
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Delete this bank record?",
                "Confirm Delete",
                javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (confirm != javax.swing.JOptionPane.YES_OPTION) {
            return;
        }

        try {
            int code = Integer.parseInt(codeText);

            String sql = "DELETE FROM Bank WHERE bankcode = ?";

            java.sql.Connection con = DBConnection.getConnection();
            java.sql.PreparedStatement pst = con.prepareStatement(sql);

            pst.setInt(1, code);

            int rows = pst.executeUpdate();

            if (rows > 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Bank record deleted successfully.");
                bankcode.setText("");
                bankname.setText("");
                bankadd.setText("");
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Bank code not found.");
            }

            pst.close();
            con.close();

        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Bank code must be a number.");
        } catch (java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error deleting record: " + ex.getMessage());
        }
    }//GEN-LAST:event_deleteActionPerformed

