    private void searchaccnumActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchaccnumActionPerformed
       String inputAccNum = JOptionPane.showInputDialog(this, "Enter Account Number to Search:");

    if (inputAccNum == null || inputAccNum.trim().isEmpty()) {
        return;
    }

    try {
        int accNumber = Integer.parseInt(inputAccNum.trim());

        String sql = "SELECT * FROM Account WHERE accnum = ?";

        Connection con = DBConnection.getConnection();
        PreparedStatement pst = con.prepareStatement(sql);
        pst.setInt(1, accNumber);

        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            DefaultTableModel model = new DefaultTableModel(
                new String[]{"Account Number", "Balance", "Account Type", "Branch Number"}, 0
            );

            model.addRow(new Object[]{
                rs.getInt("accnum"),
                rs.getDouble("balance"),
                rs.getString("acctype"),
                rs.getInt("branchnum")
            });

            JTable table = new JTable(model);

            JFrame resultFrame = new JFrame("Search Result");
            resultFrame.add(new javax.swing.JScrollPane(table));
            resultFrame.setSize(700, 150);
            resultFrame.setLocationRelativeTo(this);
            resultFrame.setVisible(true);

        } else {
            JOptionPane.showMessageDialog(this, "No record found for Account Number: " + inputAccNum);
        }

        rs.close();
        pst.close();
        con.close();

    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Account number must be a number.");
    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this, "Error searching record: " + ex.getMessage());
    }
    }//GEN-LAST:event_searchaccnumActionPerformed

