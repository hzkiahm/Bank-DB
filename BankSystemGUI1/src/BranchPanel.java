    private void updateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateActionPerformed
        String branchNumText = branchnum.getText().trim();
        String newBranchAddress = branchadd.getText().trim();
        String newBankCodeText = bankcode.getText().trim();

        if (branchNumText.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Enter branch number first.");
            branchnum.requestFocus();
            return;
        }

        if (newBranchAddress.isEmpty() || newBankCodeText.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Branch address and bank code cannot be empty.");
            return;
        }

        try {
            int branchNum = Integer.parseInt(branchNumText);
            int newBankCode = Integer.parseInt(newBankCodeText);

            java.sql.Connection con = DBConnection.getConnection();

            String selectSql = "SELECT branchadd, bankcode FROM Branch WHERE branchnum = ?";
            java.sql.PreparedStatement selectPst = con.prepareStatement(selectSql);
            selectPst.setInt(1, branchNum);
            java.sql.ResultSet rs = selectPst.executeQuery();

            if (!rs.next()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Branch number not found.");
                rs.close();
                selectPst.close();
                con.close();
                return;
            }

            String currentBranchAddress = rs.getString("branchadd");
            int currentBankCode = rs.getInt("bankcode");

            rs.close();
            selectPst.close();

            String message = "Are you sure you want to update this branch record?\n\n"
                    + "Current Information:\n"
                    + "Branch Number: " + branchNum + "\n"
                    + "Branch Address: " + currentBranchAddress + "\n"
                    + "Bank Code: " + currentBankCode + "\n\n"
                    + "New Information:\n"
                    + "Branch Number: " + branchNum + "\n"
                    + "Branch Address: " + newBranchAddress + "\n"
                    + "Bank Code: " + newBankCode;

            int confirm = javax.swing.JOptionPane.showConfirmDialog(
                    this,
                    message,
                    "Confirm Update",
                    javax.swing.JOptionPane.YES_NO_OPTION
            );

            if (confirm != javax.swing.JOptionPane.YES_OPTION) {
                con.close();
                return;
            }

            String updateSql = "UPDATE Branch SET branchadd = ?, bankcode = ? WHERE branchnum = ?";
            java.sql.PreparedStatement updatePst = con.prepareStatement(updateSql);

            updatePst.setString(1, newBranchAddress);
            updatePst.setInt(2, newBankCode);
            updatePst.setInt(3, branchNum);

            int rows = updatePst.executeUpdate();

            if (rows > 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Branch record updated successfully.");
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Update failed.");
            }

            updatePst.close();
            con.close();

        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Branch number and bank code must be numbers.");
        } catch (java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error updating record: " + ex.getMessage());
        }
    }//GEN-LAST:event_updateActionPerformed

    private void deleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteActionPerformed
        String branchNumText = branchnum.getText().trim();

        if (branchNumText.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Enter branch number first.");
            return;
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Delete this branch record?",
                "Confirm Delete",
                javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (confirm != javax.swing.JOptionPane.YES_OPTION) {
            return;
        }

        try {
            int branchNum = Integer.parseInt(branchNumText);

            String sql = "DELETE FROM Branch WHERE branchnum = ?";

            java.sql.Connection con = DBConnection.getConnection();
            java.sql.PreparedStatement pst = con.prepareStatement(sql);

            pst.setInt(1, branchNum);

            int rows = pst.executeUpdate();

            if (rows > 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Branch record deleted successfully.");
                branchnum.setText("");
                branchadd.setText("");
                bankcode.setText("");
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Branch number not found.");
            }

            pst.close();
            con.close();

        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Branch number must be a number.");
        } catch (java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error deleting record: " + ex.getMessage());
        }

    }//GEN-LAST:event_deleteActionPerformed

    private void saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveActionPerformed
        String branchNumText = branchnum.getText().trim();
        String address = branchadd.getText().trim();
        String bankCodeText = bankcode.getText().trim();

        if (branchNumText.isEmpty() || address.isEmpty() || bankCodeText.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please fill in all fields.");
            return;
        }

        try {
            int branchNum = Integer.parseInt(branchNumText);
            int bankCode = Integer.parseInt(bankCodeText);

            String sql = "INSERT INTO Branch (branchnum, branchadd, bankcode) VALUES (?, ?, ?)";

            java.sql.Connection con = DBConnection.getConnection();
            java.sql.PreparedStatement pst = con.prepareStatement(sql);

            pst.setInt(1, branchNum);
            pst.setString(2, address);
            pst.setInt(3, bankCode);

            pst.executeUpdate();

            javax.swing.JOptionPane.showMessageDialog(this, "Branch saved successfully.");

            pst.close();
            con.close();

        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Branch number and bank code must be numbers.");
        } catch (java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }
    }//GEN-LAST:event_saveActionPerformed

