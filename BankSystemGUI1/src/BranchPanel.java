    private void searchbranchnumActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchbranchnumActionPerformed
        String inputBranchNum = JOptionPane.showInputDialog(this, "Enter Branch Number to Search:");

        if (inputBranchNum == null || inputBranchNum.trim().isEmpty()) {
            return;
        }

        try {
            int branchNum = Integer.parseInt(inputBranchNum.trim());

            String sql = "SELECT * FROM Branch WHERE branchnum = ?";

            Connection con = DBConnection.getConnection();
            PreparedStatement pst = con.prepareStatement(sql);
            pst.setInt(1, branchNum);

            ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                DefaultTableModel model = new DefaultTableModel(
                    new String[]{"Branch Number", "Branch Address", "Bank Code"}, 0
                );

                model.addRow(new Object[]{
                    rs.getInt("branchnum"),
                    rs.getString("branchadd"),
                    rs.getInt("bankcode")
                });

                JTable table = new JTable(model);

                JFrame resultFrame = new JFrame("Search Result");
                resultFrame.add(new javax.swing.JScrollPane(table));
                resultFrame.setSize(600, 150);
                resultFrame.setLocationRelativeTo(this);
                resultFrame.setVisible(true);

            } else {
                JOptionPane.showMessageDialog(this, "No record found for Branch Number: " + inputBranchNum);
            }

            rs.close();
            pst.close();
            con.close();

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Branch number must be a number.");
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error searching record: " + ex.getMessage());
        }
    }//GEN-LAST:event_searchbranchnumActionPerformed

